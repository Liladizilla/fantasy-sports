#: The only leagues whose output may be committed (docs/testing.md §6).
COMMITTABLE_LEAGUES = {"1234", "99"}

ENVELOPE_KEYS = set(Envelope.success(provider="espn", data={}).to_dict())

INDEX = load_index()
JSON_SAMPLES = sorted(name for name, entry in INDEX.items() if entry["format"] == "json")
ERROR_SAMPLES = sorted(name for name, entry in INDEX.items() if entry["stream"] == "stderr")


def _read(name: str) -> str:
    return (SAMPLES_DIR / INDEX[name]["file"]).read_text(encoding="utf-8")


def _payload(name: str) -> dict:
    return json.loads(_read(name))


